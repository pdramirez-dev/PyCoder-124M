"""Score saved completions in offline, restricted Docker containers."""

import argparse

from pycoder.evaluation.functional import evaluate_samples


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("samples", help="JSON generated by generate_evaluation_samples.py")
    parser.add_argument("output", help="New JSON file for results")
    parser.add_argument("--image", default="python:3.12-alpine", help="Local Docker image")
    parser.add_argument("--timeout", type=float, default=10, help="Seconds per container")
    args = parser.parse_args()
    if args.timeout <= 0:
        parser.error("timeout must be positive")
    try:
        evaluate_samples(args.samples, args.output, args.image, args.timeout)
    except (ValueError, FileExistsError, RuntimeError) as error:
        parser.exit(1, f"Error: {error}\n")


if __name__ == "__main__":
    main()
