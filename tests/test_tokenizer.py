from pycoder.data.preprocessing import prepare, split_files
from pycoder.data.tokenizer import train_tokenizer


def test_tokenizer_and_splits(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    samples = ['def add(a, b):\n    return a + b\n', 'def square(x):\n    return x * x\n',
               'def greet():\n    return "hola"\n']
    for i, sample in enumerate(samples + samples[:1]):
        (source / f"{i}.py").write_text(sample)
    train, val, rejected = split_files(str(source))
    assert len(train) + len(val) == 3 and rejected == {"duplicate": 1}
    tok = train_tokenizer([content for _, content in train], str(tmp_path / "tok.json"), 300)
    assert tok.decode(tok.encode(samples[0]).ids) == samples[0]
    manifest = prepare(str(source), str(tmp_path / "tok.json"), str(tmp_path / "out"))
    assert set(manifest["train"]).isdisjoint(manifest["val"])
    assert (tmp_path / "out" / "train.bin").stat().st_size > 0


def test_parquet_source_and_sampling(tmp_path):
    import pyarrow as pa
    import pyarrow.parquet as pq

    from pycoder.data.download import sample_parquet

    texts = ["def a():\n    return 1\n", None, "def b():\n    return 2\n", "x = 3\n"] * 3
    shard = tmp_path / "shard.parquet"
    pq.write_table(pa.table({"text": texts, "repo_name": ["r"] * 12,
                             "path": [f"f{i}.py" for i in range(12)], "extra": [0] * 12}), shard)
    rows, total = sample_parquet([shard, shard], tmp_path / "raw" / "s.parquet", max_bytes=30)
    assert (rows, total) == (2, 44)
    sample = pq.read_table(tmp_path / "raw" / "s.parquet")
    assert sample.column_names == ["text", "repo_name", "path"]
    rows, _ = sample_parquet([shard, shard], tmp_path / "all.parquet", max_bytes=10**6)
    assert rows == 18
    train, val, _ = split_files(str(tmp_path / "raw"))
    assert {path for path, _ in train + val} == {"r/f0.py", "r/f2.py"}


def test_filter_rejection_reasons(tmp_path):
    from pycoder.config import FilterConfig
    from pycoder.data.preprocessing import rejection_reason

    config = FilterConfig(min_bytes=10, max_bytes=500)
    good = "def add(a, b):\n    return a + b\n"
    cases = {
        None: "unreadable",
        "x=1\n": "too_small",
        "x = 1\n" * 100: "too_large",
        "# " + "=" * 60 + "\n" + "x = 1\n": "low_alnum",
        "# Generated by Django 4.2\nx = 1\n": "autogenerated",
        "print 'python 2'\n": "syntax_error",
        good: None,
    }
    for content, expected in cases.items():
        assert rejection_reason(content, config) == expected, content
    wide = FilterConfig(max_bytes=5000)
    assert rejection_reason("x = '" + "a" * 1001 + "'\n", wide) == "long_line"
    assert rejection_reason(("x = '" + "a" * 150 + "'\n") * 3, wide) == "long_mean_line"
    assert rejection_reason("print 'py2'\n", FilterConfig(min_bytes=1, check_syntax=False)) is None

    source = tmp_path / "source"
    source.mkdir()
    (source / "good.py").write_text(good * 3)
    (source / "other.py").write_text(good.replace("add", "sub") * 3)
    (source / "latin1.py").write_bytes("s = 'café'\n".encode("latin-1"))
    (source / "py2.py").write_text("print 'hello world from python two'\n")
    train, val, rejected = split_files(str(source), filters=FilterConfig(min_bytes=10))
    assert len(train) + len(val) == 2
    assert rejected == {"unreadable": 1, "syntax_error": 1}


def test_byte_order_mark_is_removed(tmp_path):
    from pycoder.data.preprocessing import read_documents

    (tmp_path / "bom.py").write_bytes("\ufeffx = 1\n".encode())
    assert list(read_documents(str(tmp_path))) == [(str(tmp_path / "bom.py"), "x = 1\n")]
